#!/usr/bin/env python3
"""
Reprocess Production Test Results
=================================

This script reprocesses the existing production test results to correctly
count structures generated by multi-GPU runs.
"""

import json
import sys
from pathlib import Path

def reprocess_results(results_file):
    """Reprocess results to fix structure counts."""
    
    results_path = Path(results_file)
    if not results_path.exists():
        print(f"❌ Results file not found: {results_file}")
        return
    
    # Load existing results
    with open(results_path, 'r') as f:
        results = json.load(f)
    
    print(f"🔄 Reprocessing results from: {results_file}")
    print(f"📊 Found {len(results['configurations'])} test configurations")
    
    # Fix structure counts for each configuration
    for config in results['configurations']:
        if not config['success']:
            continue
            
        config_name = config['config_name']
        output_path = None
        
        # Find the output path
        if 'multi_gpu' in config_name:
            # Multi-GPU results
            test_dir = Path(results_file).parent
            output_path = test_dir / config_name
        else:
            # Single GPU results - extract from command
            cmd = config.get('command', '')
            if '"' in cmd:
                # Extract path from command
                parts = cmd.split('"')
                if len(parts) >= 2:
                    output_path = Path(parts[1])
        
        if not output_path or not output_path.exists():
            print(f"⚠️  Could not find output path for {config_name}")
            continue
        
        # Count structures
        original_count = config['structures_generated']
        new_count = 0
        
        # Check for multi-GPU summary
        summary_file = output_path / "multi_gpu_summary.json"
        if summary_file.exists():
            try:
                with open(summary_file, 'r') as f:
                    summary_data = json.load(f)
                
                # Calculate from batches * batch_size
                total_batches = summary_data.get('total_batches', 0)
                batch_size = 8  # Default batch size used in tests
                new_count = total_batches * batch_size
                
                print(f"🔧 {config_name}: Multi-GPU summary found")
                print(f"   Batches: {total_batches}, Batch size: {batch_size}")
                
            except Exception as e:
                print(f"❌ Error reading summary for {config_name}: {e}")
                continue
        else:
            # Count structures for single GPU
            structures_counted = 0
            
            # Check for ZIP file
            zip_files = list(output_path.glob("*crystals*.zip"))
            if zip_files:
                try:
                    import zipfile
                    for zip_file in zip_files:
                        with zipfile.ZipFile(zip_file, 'r') as zf:
                            # Count .cif files in zip
                            cif_files_in_zip = [name for name in zf.namelist() if name.endswith('.cif')]
                            structures_counted += len(cif_files_in_zip)
                    print(f"🔧 {config_name}: Found {structures_counted} structures in ZIP files")
                except Exception as e:
                    print(f"❌ Error reading ZIP files for {config_name}: {e}")
            
            # If no ZIP files, count individual CIF files
            if structures_counted == 0:
                cif_files = list(output_path.rglob("*.cif"))
                structures_counted = len(cif_files)
                print(f"🔧 {config_name}: Counted {structures_counted} individual CIF files")
            
            new_count = structures_counted
        
        # Update results
        if new_count != original_count:
            print(f"✅ {config_name}: {original_count} → {new_count} structures")
            config['structures_generated'] = new_count
            
            # Recalculate throughput
            if config['elapsed_time'] > 0:
                config['throughput_structures_per_second'] = new_count / config['elapsed_time']
            else:
                config['throughput_structures_per_second'] = 0
        else:
            print(f"✓  {config_name}: Count unchanged ({new_count})")
    
    # Save updated results
    backup_file = results_path.with_suffix('.json.backup')
    results_path.rename(backup_file)
    
    with open(results_path, 'w') as f:
        json.dump(results, f, indent=2)
    
    print(f"\n💾 Updated results saved to: {results_path}")
    print(f"📋 Backup saved to: {backup_file}")
    
    # Generate new summary
    print(f"\n📊 CORRECTED PERFORMANCE SUMMARY")
    print("="*60)
    
    successful_tests = [r for r in results['configurations'] if r['success']]
    
    # Find baseline
    baseline_time = None
    for result in successful_tests:
        if 'baseline' in result['config_name']:
            baseline_time = result['elapsed_time']
            break
    
    # Print corrected table
    header = f"{'Configuration':<25} {'Time(s)':<8} {'Structures':<12} {'Throughput/s':<12} {'Speedup':<8}"
    print(header)
    print('-' * len(header))
    
    for result in results['configurations']:
        if not result['success']:
            continue
            
        time_str = f"{result['elapsed_time']:.1f}"
        structures = str(result['structures_generated'])
        throughput = f"{result['throughput_structures_per_second']:.2f}"
        
        speedup = ""
        if baseline_time and result['elapsed_time'] > 0:
            speedup_factor = baseline_time / result['elapsed_time']
            speedup = f"{speedup_factor:.2f}x"
        
        print(f"{result['config_name']:<25} {time_str:<8} {structures:<12} {throughput:<12} {speedup:<8}")
    
    print(f"\n🎉 Results successfully reprocessed!")

def main():
    if len(sys.argv) != 2:
        print("Usage: python reprocess_results.py <results_file.json>")
        print("\nExample:")
        print("  python reprocess_results.py production_demo/test_20250627_152656/production_test_results.json")
        sys.exit(1)
    
    results_file = sys.argv[1]
    reprocess_results(results_file)

if __name__ == "__main__":
    main()
